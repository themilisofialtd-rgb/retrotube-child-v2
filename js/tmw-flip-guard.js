(function () {
  try {
    var isTouch = matchMedia('(pointer: coarse)').matches || 'ontouchstart' in window;
    if (!isTouch) return;
    var guardState = new WeakMap();
    var ARM_WINDOW_MS = 1000;

    function armGuard(root, anchor) {
      var state = guardState.get(root);
      if (state && state.timer) {
        clearTimeout(state.timer);
      }

      var timer = setTimeout(function () {
        guardState.delete(root);
      }, ARM_WINDOW_MS);

      guardState.set(root, { anchor: anchor, timer: timer });
    }

    document.addEventListener('click', function (e) {
      // Only guard within flip cards generated by our templates
      var card = e.target.closest('.tmw-flip, .tmw-flip-inner, .tmw-flip-front, .tmw-flip-back');
      if (!card) return;
      // If a template set data-mobile-guard="true", prevent navigation
      var root = card.closest('[data-mobile-guard="true"]');
      if (!root) return;
      var anchor = e.target.closest('a');
      if (anchor) {
        var state = guardState.get(root);
        if (!state || state.anchor !== anchor) {
          armGuard(root, anchor);
          e.preventDefault();
          e.stopPropagation();
          // Let the template’s JS/CSS handle the flip on the first tap.
          return;
        }

        // Second tap within the guard window should proceed with navigation.
        if (state && state.timer) {
          clearTimeout(state.timer);
        }
        guardState.delete(root);
      }
    }, { capture: true });
  } catch (_) {}
})();
